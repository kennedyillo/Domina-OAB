create table if not exists public.pilot_leads (
  id bigint generated by default as identity primary key,
  email text not null unique,
  status text not null default 'founder' check (status = 'founder'),
  consent_version text not null default '2026-09',
  created_at timestamptz not null default now()
);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('page_view','simulado_started','simulado_completed')),
  path text not null default '/',
  session_id text not null,
  referrer text not null default '',
  utm_source text not null default '',
  utm_medium text not null default '',
  utm_campaign text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists analytics_events_type_created_idx
  on public.analytics_events(event_type, created_at);
create index if not exists analytics_events_session_idx
  on public.analytics_events(session_id);

create table if not exists public.plans (
  id text primary key,
  slug text not null unique,
  name text not null,
  billing_type text not null check (billing_type in ('recurring','one_time','promotional')),
  duration_days integer,
  price_cents integer not null check (price_cents >= 0),
  max_installments integer not null default 1 check (max_installments >= 1),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  email text not null,
  plan_id text not null references public.plans(id),
  provider text not null default 'mercado_pago',
  provider_subscription_id text unique,
  status text not null default 'pending',
  starts_at timestamptz,
  current_period_end timestamptz,
  next_charge_at timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists subscriptions_user_status_idx
  on public.subscriptions(user_id, status);
create index if not exists subscriptions_email_idx
  on public.subscriptions(email);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  email text not null,
  plan_id text not null references public.plans(id),
  subscription_id bigint references public.subscriptions(id) on delete set null,
  provider text not null default 'mercado_pago',
  provider_payment_id text unique,
  status text not null default 'pending',
  payment_method text,
  installments integer not null default 1,
  gross_amount_cents integer not null,
  fee_amount_cents integer not null default 0,
  net_amount_cents integer not null default 0,
  approved_at timestamptz,
  available_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists payments_status_created_idx
  on public.payments(status, created_at);
create index if not exists payments_user_idx
  on public.payments(user_id);

create table if not exists public.entitlements (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  email text not null,
  plan_id text not null references public.plans(id),
  source_type text not null,
  source_id text,
  status text not null default 'pending',
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists entitlements_user_status_idx
  on public.entitlements(user_id, status);
create index if not exists entitlements_email_idx
  on public.entitlements(email);

create table if not exists public.payment_events (
  id bigint generated by default as identity primary key,
  provider text not null default 'mercado_pago',
  provider_event_id text not null unique,
  event_type text not null,
  resource_id text,
  processing_status text not null default 'received',
  payload text not null,
  error_message text,
  received_at timestamptz not null default now(),
  processed_at timestamptz
);

create index if not exists payment_events_status_received_idx
  on public.payment_events(processing_status, received_at);

