create or replace function public.founder_availability()
returns jsonb
language sql
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'remaining', greatest(0, 25 - count(*)),
    'limit', 25
  )
  from public.pilot_leads
  where status = 'founder';
$$;

create or replace function public.register_founder(
  p_email text,
  p_consent_version text default '2026-09'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email text := lower(trim(p_email));
  v_total integer;
  v_inserted boolean := false;
begin
  if v_email = '' or length(v_email) > 254 then
    raise exception 'invalid_email';
  end if;

  lock table public.pilot_leads in share row exclusive mode;

  if exists (select 1 from public.pilot_leads where email = v_email) then
    select count(*) into v_total
    from public.pilot_leads
    where status = 'founder';

    return jsonb_build_object(
      'status','founder',
      'remaining',greatest(0,25-v_total),
      'inserted',false
    );
  end if;

  select count(*) into v_total
  from public.pilot_leads
  where status = 'founder';

  if v_total >= 25 then
    return jsonb_build_object(
      'closed',true,
      'remaining',0,
      'error','As vagas gratuitas foram preenchidas.'
    );
  end if;

  insert into public.pilot_leads(email,status,consent_version)
  values (
    v_email,
    'founder',
    coalesce(nullif(p_consent_version,''),'2026-09')
  );

  v_inserted := true;

  select count(*) into v_total
  from public.pilot_leads
  where status = 'founder';

  return jsonb_build_object(
    'status','founder',
    'remaining',greatest(0,25-v_total),
    'inserted',v_inserted
  );
end;
$$;

create or replace function public.record_analytics(
  p_event_type text,
  p_path text,
  p_session_id text,
  p_referrer text default '',
  p_utm_source text default '',
  p_utm_medium text default '',
  p_utm_campaign text default ''
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_event_type not in ('page_view','simulado_started','simulado_completed') then
    raise exception 'invalid_event';
  end if;

  if coalesce(trim(p_session_id),'') = '' then
    raise exception 'invalid_session';
  end if;

  insert into public.analytics_events(
    event_type,path,session_id,referrer,utm_source,utm_medium,utm_campaign
  )
  values (
    left(p_event_type,40),
    left(coalesce(nullif(p_path,''),'/'),300),
    left(p_session_id,80),
    left(coalesce(p_referrer,''),500),
    left(coalesce(p_utm_source,''),120),
    left(coalesce(p_utm_medium,''),120),
    left(coalesce(p_utm_campaign,''),160)
  );
end;
$$;

