create table if not exists public.disciplines (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  position integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.question_topics (
  id bigint generated by default as identity primary key,
  discipline_id bigint not null references public.disciplines(id) on delete cascade,
  name text not null,
  slug text not null,
  position integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(discipline_id,slug)
);

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  code text not null unique,
  discipline_id bigint not null references public.disciplines(id),
  topic_id bigint references public.question_topics(id) on delete set null,
  statement text not null,
  options jsonb not null,
  correct_index integer not null check (correct_index between 0 and 3),
  explanation text not null,
  source_label text,
  difficulty text not null default 'medium' check (difficulty in ('easy','medium','hard')),
  status text not null default 'draft' check (status in ('draft','published','archived')),
  position integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (jsonb_typeof(options)='array' and jsonb_array_length(options)=4)
);

create index if not exists questions_discipline_status_idx on public.questions(discipline_id,status,position,id);
create index if not exists questions_topic_idx on public.questions(topic_id,status);

create table if not exists public.question_reports (
  id bigint generated by default as identity primary key,
  question_id bigint not null references public.questions(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  reason text not null check (reason in ('gabarito','enunciado','explicacao','desatualizada','duplicada','outro')),
  message text,
  status text not null default 'open' check (status in ('open','reviewing','resolved','dismissed')),
  resolution_note text,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists question_reports_status_created_idx on public.question_reports(status,created_at desc);
create index if not exists question_reports_question_idx on public.question_reports(question_id,status);

alter table public.disciplines enable row level security;
alter table public.question_topics enable row level security;
alter table public.questions enable row level security;
alter table public.question_reports enable row level security;

