create or replace function public.public_questions(p_discipline_slug text)
returns jsonb
language sql
security definer
set search_path=public
as $$
  select coalesce(jsonb_agg(to_jsonb(x) order by x.position,x.id),'[]'::jsonb)
  from (
    select q.id,q.code,d.slug discipline_slug,d.name discipline,t.name topic,q.statement,q.options,q.difficulty,q.position
    from public.questions q
    join public.disciplines d on d.id=q.discipline_id
    left join public.question_topics t on t.id=q.topic_id
    where d.slug=p_discipline_slug and d.active=true and q.status='published'
    order by q.position,q.id
  ) x;
$$;

create or replace function public.verify_question(p_question_id bigint,p_option integer)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare q public.questions%rowtype;
begin
  select * into q from public.questions where id=p_question_id and status='published';
  if not found then raise exception 'question_not_found'; end if;
  if p_option < 0 or p_option > 3 then raise exception 'invalid_option'; end if;
  return jsonb_build_object('correct',p_option=q.correct_index,'correct_index',q.correct_index,'explanation',q.explanation);
end;
$$;

create or replace function public.report_question(p_question_id bigint,p_reason text,p_message text default null)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare v_id bigint;
begin
  if p_reason not in ('gabarito','enunciado','explicacao','desatualizada','duplicada','outro') then raise exception 'invalid_reason'; end if;
  if not exists(select 1 from public.questions where id=p_question_id and status='published') then raise exception 'question_not_found'; end if;
  insert into public.question_reports(question_id,user_id,reason,message)
  values(p_question_id,auth.uid(),p_reason,nullif(left(trim(coalesce(p_message,'')),1000),'')) returning id into v_id;
  return jsonb_build_object('ok',true,'report_id',v_id);
end;
$$;

create or replace function public.admin_questions(p_query text default null,p_status text default null)
returns jsonb
language sql
security definer
set search_path=public
as $$
  select coalesce(jsonb_agg(to_jsonb(x) order by x.updated_at desc),'[]'::jsonb)
  from (
    select q.id,q.code,d.slug discipline_slug,d.name discipline,t.id topic_id,t.name topic,q.statement,q.options,q.correct_index,q.explanation,q.source_label,q.difficulty,q.status,q.position,q.created_at,q.updated_at,
      (select count(*)::int from public.question_reports r where r.question_id=q.id and r.status in ('open','reviewing')) open_reports
    from public.questions q
    join public.disciplines d on d.id=q.discipline_id
    left join public.question_topics t on t.id=q.topic_id
    where (coalesce(trim(p_status),'')='' or q.status=p_status)
      and (coalesce(trim(p_query),'')='' or lower(q.code) like '%'||lower(trim(p_query))||'%' or lower(q.statement) like '%'||lower(trim(p_query))||'%' or lower(coalesce(t.name,'')) like '%'||lower(trim(p_query))||'%')
    order by q.updated_at desc
    limit 300
  ) x;
$$;

create or replace function public.admin_save_question(
  p_id bigint,
  p_code text,
  p_discipline_slug text,
  p_topic text,
  p_statement text,
  p_options jsonb,
  p_correct_index integer,
  p_explanation text,
  p_source_label text,
  p_difficulty text,
  p_status text
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare v_discipline bigint; v_topic bigint; v_id bigint; v_topic_slug text;
begin
  if jsonb_typeof(p_options)<>'array' or jsonb_array_length(p_options)<>4 then raise exception 'four_options_required'; end if;
  if p_correct_index not between 0 and 3 then raise exception 'invalid_correct_index'; end if;
  if p_difficulty not in ('easy','medium','hard') then raise exception 'invalid_difficulty'; end if;
  if p_status not in ('draft','published','archived') then raise exception 'invalid_status'; end if;
  select id into v_discipline from public.disciplines where slug=p_discipline_slug;
  if v_discipline is null then raise exception 'discipline_not_found'; end if;
  v_topic_slug := lower(regexp_replace(trim(p_topic),'[^a-zA-Z0-9]+','-','g'));
  select id into v_topic from public.question_topics where discipline_id=v_discipline and lower(name)=lower(trim(p_topic)) limit 1;
  if v_topic is null then
    insert into public.question_topics(discipline_id,name,slug,position) values(v_discipline,trim(p_topic),v_topic_slug,999)
    on conflict(discipline_id,slug) do update set name=excluded.name,updated_at=now() returning id into v_topic;
  end if;
  if p_id is null then
    insert into public.questions(code,discipline_id,topic_id,statement,options,correct_index,explanation,source_label,difficulty,status,position)
    values(upper(trim(p_code)),v_discipline,v_topic,trim(p_statement),p_options,p_correct_index,trim(p_explanation),nullif(trim(p_source_label),''),p_difficulty,p_status,999)
    returning id into v_id;
  else
    update public.questions set code=upper(trim(p_code)),discipline_id=v_discipline,topic_id=v_topic,statement=trim(p_statement),options=p_options,correct_index=p_correct_index,explanation=trim(p_explanation),source_label=nullif(trim(p_source_label),''),difficulty=p_difficulty,status=p_status,updated_at=now()
    where id=p_id returning id into v_id;
    if v_id is null then raise exception 'question_not_found'; end if;
  end if;
  return jsonb_build_object('ok',true,'id',v_id);
end;
$$;

create or replace function public.admin_set_question_status(p_id bigint,p_status text)
returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if p_status not in ('draft','published','archived') then raise exception 'invalid_status'; end if;
  update public.questions set status=p_status,updated_at=now() where id=p_id;
  if not found then raise exception 'question_not_found'; end if;
end;
$$;

create or replace function public.admin_reports(p_status text default null)
returns jsonb
language sql
security definer
set search_path=public
as $$
  select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc),'[]'::jsonb)
  from (
    select r.id,r.question_id,q.code,q.statement,d.name discipline,t.name topic,r.reason,r.message,r.status,r.resolution_note,r.created_at,r.resolved_at,
      coalesce(p.email,u.email) reporter_email
    from public.question_reports r
    join public.questions q on q.id=r.question_id
    join public.disciplines d on d.id=q.discipline_id
    left join public.question_topics t on t.id=q.topic_id
    left join public.user_profiles p on p.user_id=r.user_id
    left join auth.users u on u.id=r.user_id
    where coalesce(trim(p_status),'')='' or r.status=p_status
    order by r.created_at desc
    limit 300
  ) x;
$$;

create or replace function public.admin_resolve_report(p_id bigint,p_status text,p_note text default null)
returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if p_status not in ('reviewing','resolved','dismissed') then raise exception 'invalid_status'; end if;
  update public.question_reports
  set status=p_status,resolution_note=nullif(left(trim(coalesce(p_note,'')),1000),''),resolved_at=case when p_status in ('resolved','dismissed') then now() else null end,updated_at=now()
  where id=p_id;
  if not found then raise exception 'report_not_found'; end if;
end;
$$;

